import { expect, test } from '@playwright/test'

test('framework save synchronizes catalog; dirty navigation and stale edits are safe', async ({ page, request }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const created = await request.post('/api/integrations', { data: { name: `Browser smoke ${Date.now()}` } })
  expect(created.ok()).toBeTruthy()
  const integration = await created.json()
  const path = `/api/integrations/${integration.id}`
  await page.goto(`/integrations/${integration.id}`)
  await expect(page.getByRole('button', { name: 'Edit framework', exact: true })).toBeEnabled()
  await page.screenshot({ path: testInfo.outputPath('desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Edit framework', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeDisabled()
  await page.getByLabel('Business owner', { exact: true }).fill('Synthetic Operations')
  await page.getByRole('button', { name: 'Save framework', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit framework', exact: true })).toBeEnabled()
  expect((await (await request.get(path)).json()).version).toBe(2)
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Description', { exact: true }).fill('Saved after framework edit')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeEnabled()
  expect((await (await request.get(path)).json()).description).toBe('Saved after framework edit')
  await page.getByRole('button', { name: 'Edit framework', exact: true }).click()
  await page.getByLabel('Business owner', { exact: true }).fill('Unsaved only')
  await page.getByRole('link', { name: 'View DAG', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByLabel('Business owner', { exact: true })).toHaveValue('Unsaved only')
  const profile = await (await request.get(`${path}/framework`)).json()
  profile.spec.ownership.support_team = 'Concurrent editor'
  const external = await request.put(`${path}/framework`, { data: { version: profile.version, spec: profile.spec } })
  expect(external.ok()).toBeTruthy()
  await page.getByRole('button', { name: 'Save framework', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reload saved profile', exact: true })).toBeVisible()
  // Conflict switches to read-only rendering but retains the local draft for copying.
  await expect(page.getByText('Unsaved only', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reload saved profile', exact: true }).click()
  await page.getByRole('button', { name: 'Discard and reload', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit framework', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Description', { exact: true }).fill('Saved after conflict reload')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeEnabled()
  expect((await (await request.get(path)).json()).description).toBe('Saved after conflict reload')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})

test('general users see read-only framework and retired catalog cannot be edited', async ({ page, request }) => {
  const created = await request.post('/api/integrations', { data: { name: `Role smoke ${Date.now()}` } })
  const integration = await created.json()
  await page.route('**/api/me', async route => {
    const response = await route.fetch()
    const me = await response.json()
    await route.fulfill({ response, json: { ...me, is_admin: false, user: { ...me.user, role: 'general' } } })
  })
  await page.goto(`/integrations/${integration.id}`)
  await expect(page.getByText('Read-only access', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Edit framework', exact: true })).toHaveCount(0)
  await page.unroute('**/api/me')
  await page.route(`**/api/integrations/${integration.id}/framework`, async route => {
    const response = await route.fetch()
    const profile = await response.json()
    await route.fulfill({ response, json: { ...profile, stage: 'retired', version: 1 } })
  })
  await page.reload()
  await expect(page.getByRole('button', { name: 'Edit', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Edit framework', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Record release plan', exact: true })).toHaveCount(0)
})

test('approval readiness refreshes and material spec edits invalidate approval display', async ({ page, request }) => {
  const created = await request.post('/api/integrations', { data: { name: `Approval smoke ${Date.now()}` } })
  const integration = await created.json()
  const path = `/api/integrations/${integration.id}`
  expect((await request.put(`${path}/framework`, { data: { version: 0, spec: {} } })).ok()).toBeTruthy()
  await page.goto(`/integrations/${integration.id}`)
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByLabel('Design approved', { exact: true }).check()
  await page.getByLabel('Code approved', { exact: true }).check()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const approvalCheck = page.locator('.framework-readiness li').filter({ hasText: 'Design and code approval records' })
  await expect(approvalCheck).toHaveClass('passed')
  await page.getByRole('button', { name: 'Edit framework', exact: true }).click()
  await page.getByLabel('Business owner', { exact: true }).fill('Changed ownership requires review')
  await page.getByRole('button', { name: 'Save framework', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Edit framework', exact: true })).toBeEnabled()
  await expect(approvalCheck).not.toHaveClass('passed')
  const detail = await (await request.get(path)).json()
  expect(detail.design_approved).toBe(false)
  expect(detail.code_approved).toBe(false)
  await expect(page.getByText('Not approved', { exact: true })).toHaveCount(2)
})
